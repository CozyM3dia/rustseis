/// Trace type codes aligned with ProMAX `TRC_TYPE` and SEG-Y/SEG-D conventions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[repr(i32)]
pub enum TraceType {
    Dead = 0,
    #[default]
    Live = 1,
    Auxiliary = 9,
}

impl TraceType {
    pub fn from_i32(v: i32) -> Self {
        match v {
            0 => Self::Dead,
            9 => Self::Auxiliary,
            _ => Self::Live,
        }
    }
}

